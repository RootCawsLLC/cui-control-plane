#!/usr/bin/env node
// Generates reference/nist-800-171r2.index.yaml and reference/sprs-weights.yaml.
//
// The index is generated rather than hand-typed for one reason: the family counts are the
// thing most easily got wrong, and a generator that declares 3.1 runs to .22 and then emits
// exactly 22 identifiers is checkable in a way that 110 typed lines is not. tests/index.test.mjs
// re-runs this and diffs, so a hand edit to the committed file fails CI.
//
// WHAT IS DELIBERATELY ABSENT: requirement text. NIST SP 800-171 is a US Government work and
// therefore public domain, so reproducing it would be lawful - it is left out because it is not
// ours to restate and would go stale against the authority. Per ADR 0006 the whole repository
// holds framework *identifiers* and our own reasoning, and nothing else. Requirement text is
// resolved at read time from the authority, never mirrored here.
//
// Assessment-objective counts per requirement come from NIST SP 800-171A, which this repository
// does not mirror either, so `assessment_objectives` is null everywhere until someone populates
// it from the source. 320 objectives across the 110 is the published total and is recorded as a
// checkable expectation, not as a per-requirement guess.

import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * The fourteen families of 800-171 Rev 2 and the highest requirement number in each.
 * Abbreviations are the family abbreviations used by the source; `last` is the only datum
 * here that can be wrong, and the total is what catches it.
 */
export const FAMILIES = [
  { family: '3.1', abbrev: 'AC', name: 'Access Control', last: 22 },
  { family: '3.2', abbrev: 'AT', name: 'Awareness and Training', last: 3 },
  { family: '3.3', abbrev: 'AU', name: 'Audit and Accountability', last: 9 },
  { family: '3.4', abbrev: 'CM', name: 'Configuration Management', last: 9 },
  { family: '3.5', abbrev: 'IA', name: 'Identification and Authentication', last: 11 },
  { family: '3.6', abbrev: 'IR', name: 'Incident Response', last: 3 },
  { family: '3.7', abbrev: 'MA', name: 'Maintenance', last: 6 },
  { family: '3.8', abbrev: 'MP', name: 'Media Protection', last: 9 },
  { family: '3.9', abbrev: 'PS', name: 'Personnel Security', last: 2 },
  { family: '3.10', abbrev: 'PE', name: 'Physical Protection', last: 6 },
  { family: '3.11', abbrev: 'RA', name: 'Risk Assessment', last: 3 },
  { family: '3.12', abbrev: 'CA', name: 'Security Assessment', last: 4 },
  { family: '3.13', abbrev: 'SC', name: 'System and Communications Protection', last: 16 },
  { family: '3.14', abbrev: 'SI', name: 'System and Information Integrity', last: 7 },
];

export const EXPECTED_REQUIREMENTS = 110;
export const EXPECTED_ASSESSMENT_OBJECTIVES = 320;

/**
 * Requirements that cannot be carried on a POA&M regardless of SPRS score. Held as an
 * explicitly UNVERIFIED list rather than omitted, because "we forgot to check" and "we checked
 * and it is empty" must not look the same. Populate from the live 32 CFR Part 170 text; the
 * validator refuses to let a POA&M include any requirement marked non-poamable, and warns
 * loudly for as long as the list is unverified.
 */
export const NON_POAMABLE = {
  verified: false,
  source: '32 CFR Part 170 - read the live text, not a secondary source',
  identifiers: [],
};

export function requirements() {
  const out = [];
  for (const f of FAMILIES) {
    for (let n = 1; n <= f.last; n += 1) {
      out.push({
        id: `${f.family}.${n}`,
        family: f.family,
        family_abbrev: f.abbrev,
        family_name: f.name,
        assessment_objectives: null,
      });
    }
  }
  return out;
}

function yamlIndex(reqs) {
  const lines = [
    '# GENERATED by scripts/gen-requirement-index.mjs - do not hand edit.',
    '# NIST SP 800-171 Rev 2 requirement identifiers. Identifiers only: no requirement text.',
    '#',
    '# Rev 2, not Rev 3, on purpose. CMMC is legally pinned to Rev 2 - 32 CFR 170.2 incorporates',
    '# the February 2020 revision by reference - while NIST published Rev 3 in 2024 and',
    '# usnistgov/oscal-content ships an OSCAL catalog for Rev 3 only. NIST publishes OSCAL for the',
    '# revision that does not legally apply, which is why this repository authors its own catalog.',
    '# See docs/adr/0002 and docs/watch-items.md.',
    '#',
    '# This is the ASSESSMENT TARGET, not the control inventory. Our controls live in controls/',
    '# and crosswalk to these identifiers many-to-many; see docs/adr/0002.',
    '',
    'revision: "Rev 2"',
    `requirement_count: ${reqs.length}`,
    `assessment_objective_count_published: ${EXPECTED_ASSESSMENT_OBJECTIVES}`,
    'assessment_objective_source: "NIST SP 800-171A - not mirrored here; per-requirement counts are null until populated from it"',
    '',
    'families:',
  ];
  for (const f of FAMILIES) {
    lines.push(`  - family: "${f.family}"`);
    lines.push(`    abbrev: ${f.abbrev}`);
    lines.push(`    name: "${f.name}"`);
    lines.push(`    count: ${f.last}`);
  }
  lines.push('');
  lines.push('non_poamable:');
  lines.push(`  verified: ${NON_POAMABLE.verified}`);
  lines.push(`  source: "${NON_POAMABLE.source}"`);
  lines.push(
    '  note: "Several requirements cannot be carried on a POA&M regardless of score. Until verified: false becomes true this list is empty because nobody has checked, NOT because it is empty."'
  );
  lines.push(`  identifiers: [${NON_POAMABLE.identifiers.join(', ')}]`);
  lines.push('');
  lines.push('requirements:');
  for (const r of reqs) {
    lines.push(`  - id: "${r.id}"`);
    lines.push(`    family: "${r.family}"`);
    lines.push(`    family_abbrev: ${r.family_abbrev}`);
    lines.push(`    assessment_objectives: ${r.assessment_objectives ?? 'null'}`);
  }
  return `${lines.join('\n')}\n`;
}

function yamlWeights(reqs) {
  const lines = [
    '# GENERATED by scripts/gen-requirement-index.mjs - do not hand edit.',
    '#',
    '# SPRS scoring under the NIST SP 800-171 DoD Assessment Methodology. The score starts at 110',
    '# and each unimplemented requirement subtracts its weight.',
    '#',
    '# EVERY WEIGHT BELOW IS null AND THAT IS THE POINT. The 5 / 3 / 1 weighting scheme and the two',
    '# partial-credit rules are structural and are encoded in src/sprs.mjs. The per-requirement',
    '# weight assignment is a published table in the DoD Assessment Methodology, and this repository',
    '# will not ship a guess at it: a wrong weight produces a wrong SPRS score, a wrong SPRS score is',
    '# submitted to a Government system of record, and it would be indistinguishable from a right one',
    '# by inspection. src/sprs.mjs REFUSES to compute a score while any in-scope weight is null and',
    '# names the offenders.',
    '#',
    '# To populate: read the current DoD Assessment Methodology, set weight and set verified: true.',
    '# fixtures/sprs-weights.fixture.yaml exists so the scorer can be exercised and tested; it is',
    '# stamped NOT REAL WEIGHTS and the scorer refuses to call its output submittable.',
    '',
    'verified: false',
    'source: "NIST SP 800-171 DoD Assessment Methodology - populate from the current version"',
    'scheme:',
    '  basis: 110',
    '  weights: [5, 3, 1]',
    'partial_credit:',
    '  - id: "3.5.3"',
    '    rule: "multifactor authentication implemented for some but not all required access - deduct 3 rather than 5"',
    '    verified: false',
    '  - id: "3.13.11"',
    '    rule: "cryptography employed but not FIPS-validated - deduct 3 rather than 5"',
    '    verified: false',
    '',
    'weights:',
  ];
  for (const r of reqs) {
    lines.push(`  - id: "${r.id}"`);
    lines.push('    weight: null');
  }
  return `${lines.join('\n')}\n`;
}

/**
 * A weights file that lets the scorer be exercised without anybody mistaking it for the real
 * table. Every weight is 5 - not a guess at the published distribution, just a uniform value that
 * makes the arithmetic testable. `verified: false` is what actually matters: it forces
 * `submittable: false` out of src/sprs.mjs no matter how clean the evidence set is.
 */
function yamlFixtureWeights(reqs) {
  const lines = [
    '# GENERATED by scripts/gen-requirement-index.mjs - do not hand edit.',
    '#',
    '# NOT REAL WEIGHTS. Every weight here is a uniform 5. This file exists so the SPRS arithmetic',
    '# can be exercised and tested; it is NOT the published DoD Assessment Methodology table and a',
    '# score computed from it is not a score. verified: false keeps src/sprs.mjs from ever calling',
    '# its output submittable.',
    '',
    'verified: false',
    'source: "FIXTURE - uniform weight of 5, not the published table"',
    'scheme:',
    '  basis: 110',
    '  weights: [5, 3, 1]',
    '',
    'weights:',
  ];
  for (const r of reqs) {
    lines.push(`  - id: "${r.id}"`);
    lines.push('    weight: 5');
  }
  return `${lines.join('\n')}\n`;
}

const reqs = requirements();
if (reqs.length !== EXPECTED_REQUIREMENTS) {
  console.error(
    `refusing to write: generated ${reqs.length} requirements, expected ${EXPECTED_REQUIREMENTS}. ` +
      'One of the family "last" values in FAMILIES is wrong.'
  );
  process.exit(1);
}

writeFileSync(join(root, 'reference', 'nist-800-171r2.index.yaml'), yamlIndex(reqs));
writeFileSync(join(root, 'reference', 'sprs-weights.yaml'), yamlWeights(reqs));
writeFileSync(join(root, 'fixtures', 'sprs-weights.fixture.yaml'), yamlFixtureWeights(reqs));
console.log(`wrote ${reqs.length} requirements across ${FAMILIES.length} families`);
